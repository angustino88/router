-- Same tables, columns and constraints as the Django migration tenant/0001_initial.py,
-- so the Rust service and the Django admin can share one database.
-- Safe to run repeatedly. If Django is pointed at a database created here, run
-- `python manage.py migrate --fake-initial` once.

CREATE TABLE IF NOT EXISTS tenant_backend (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created                timestamptz  NOT NULL DEFAULT now(),
    modified               timestamptz  NOT NULL DEFAULT now(),
    prefix_key             varchar(100) NOT NULL UNIQUE,
    name                   varchar(255) NOT NULL,
    is_active              boolean      NOT NULL DEFAULT true,
    computer_sync_version  integer      NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS tenant_usertenantresolver (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created       timestamptz  NOT NULL DEFAULT now(),
    modified      timestamptz  NOT NULL DEFAULT now(),
    user_id       varchar(255) NOT NULL,
    display_name  varchar(255) NOT NULL DEFAULT '',
    is_active     boolean      NOT NULL DEFAULT true,
    backend_id    bigint       NOT NULL REFERENCES tenant_backend (id) DEFERRABLE INITIALLY DEFERRED,
    UNIQUE (user_id, backend_id)
);
CREATE INDEX IF NOT EXISTS tenant_usertenantresolver_backend_id_idx ON tenant_usertenantresolver (backend_id);

CREATE TABLE IF NOT EXISTS tenant_agenttenantresolver (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created     timestamptz  NOT NULL DEFAULT now(),
    modified    timestamptz  NOT NULL DEFAULT now(),
    agent_id    varchar(255) NOT NULL,
    sku         varchar(255) NOT NULL DEFAULT '',
    is_active   boolean      NOT NULL DEFAULT true,
    backend_id  bigint       NOT NULL REFERENCES tenant_backend (id) DEFERRABLE INITIALLY DEFERRED,
    UNIQUE (agent_id, backend_id)
);
CREATE INDEX IF NOT EXISTS tenant_agenttenantresolver_backend_id_idx ON tenant_agenttenantresolver (backend_id);

-- ---------------------------------------------------------------------------
-- Replacement for Celery beat (django_celery_beat) and the Celery result backend.

-- One row per periodic task; edited from the admin page.
CREATE TABLE IF NOT EXISTS rust_periodic_task (
    name           text        PRIMARY KEY,
    enabled        boolean     NOT NULL DEFAULT true,
    interval_secs  integer     NOT NULL CHECK (interval_secs > 0),
    last_run_at    timestamptz,
    updated_at     timestamptz NOT NULL DEFAULT now()
);

-- History of task runs (scheduled and manual), newest kept, older pruned.
CREATE TABLE IF NOT EXISTS rust_task_run (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task         text        NOT NULL,
    trigger      text        NOT NULL,            -- 'schedule' | 'manual'
    status       text        NOT NULL,            -- 'running' | 'succeeded' | 'failed'
    started_at   timestamptz NOT NULL DEFAULT now(),
    finished_at  timestamptz,
    result       jsonb,
    error        text
);
CREATE INDEX IF NOT EXISTS rust_task_run_task_id_idx ON rust_task_run (task, id DESC);

-- Backend URL used to generate the nginx admin map (scheme://host[:port]). Empty = not routed by the
-- generated map (it may still be in the git-managed backends.map). Django ignores this column; its
-- default lets the old Django admin keep inserting rows.
ALTER TABLE tenant_backend ADD COLUMN IF NOT EXISTS upstream_url varchar(255) NOT NULL DEFAULT '';

-- ---------------------------------------------------------------------------
-- Routing sync with the core backends (GET /internal/snapshot|changes/{users,agents}).
-- tenant_usertenantresolver.user_id now holds the routing key `entra:<tenant UUID>:<object UUID>`
-- (display_name is no longer filled); tenant_agenttenantresolver.agent_id holds the agent UUID.

-- Last applied position of each (backend, stream): the epoch and version of the core change stream.
CREATE TABLE IF NOT EXISTS rust_sync_cursor (
    backend_id  bigint      NOT NULL REFERENCES tenant_backend (id) ON DELETE CASCADE,
    entity      text        NOT NULL CHECK (entity IN ('users', 'agents')),
    epoch       text        NOT NULL,
    version     bigint      NOT NULL CHECK (version >= 0),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (backend_id, entity)
);

-- ---------------------------------------------------------------------------
-- Registry entry of each backend (routing-spec CNS-1/CNS-2): the logical `backend_id` the backend reports in
-- GET /internal/info (its BACKEND_ID setting). Empty = not verified (and not usable with Entra sync auth,
-- whose token audience is derived from it). Two rows can never claim the same logical backend.
ALTER TABLE tenant_backend ADD COLUMN IF NOT EXISTS backend_id varchar(100) NOT NULL DEFAULT '';
CREATE UNIQUE INDEX IF NOT EXISTS tenant_backend_backend_id_uniq ON tenant_backend (backend_id) WHERE backend_id <> '';

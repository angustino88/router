//! Maintenance commands (run inside the container with `docker compose exec tenant_resolver tenant-resolver ...`).

use anyhow::{bail, Result};
use clap::Subcommand;
use sqlx::PgPool;

use crate::{
    db::backends::{self as backend_db, random_prefix_key, valid_prefix_key},
    jobs::sync::{Syncer, Task},
    settings::Settings,
};

#[derive(Subcommand)]
pub enum BackendCmd {
    /// List all backends.
    List,
    /// Create a backend. Without --prefix-key a random 10-character key is generated (like the admin).
    Add {
        #[arg(long)]
        name: String,
        #[arg(long)]
        prefix_key: Option<String>,
        /// Backend URL nginx proxies `/t/<prefix_key>/` to, e.g. https://lab-a.example.com:8443
        #[arg(long)]
        url: Option<String>,
        /// The backend's BACKEND_ID, checked against GET /internal/info
        #[arg(long)]
        backend_id: Option<String>,
        #[arg(long)]
        inactive: bool,
    },
    /// Mark a backend active.
    Activate { prefix_key: String },
    /// Mark a backend inactive.
    Deactivate { prefix_key: String },
}

/// Full resync (snapshot + replay) of one stream on every active backend, then prints the result.
pub async fn sync_once(pool: PgPool, s: &Settings, task: Task) -> Result<()> {
    let result = Syncer::new(pool, s)?.sync_all(task, true).await?;
    println!("{}", serde_json::to_string_pretty(&result)?);
    Ok(())
}

pub async fn backend(pool: &PgPool, cmd: BackendCmd) -> Result<()> {
    match cmd {
        BackendCmd::List => {
            println!("{:<6} {:<14} {:<8} {:<14} {:<36} name", "id", "prefix_key", "active", "backend_id", "url");
            for b in backend_db::all_backends(pool).await? {
                println!(
                    "{:<6} {:<14} {:<8} {:<14} {:<36} {}",
                    b.id, b.prefix_key, b.is_active, b.backend_id, b.upstream_url, b.name
                );
            }
        }
        BackendCmd::Add { name, prefix_key, url, backend_id, inactive } => {
            let name = name.trim().to_string();
            if name.is_empty() || name.len() > 255 {
                bail!("--name must be 1..255 characters");
            }
            let key = match prefix_key {
                Some(k) if valid_prefix_key(&k) => k,
                Some(k) => bail!("invalid --prefix-key {k:?} (use letters, digits, '_' or '-')"),
                None => loop {
                    let k = random_prefix_key(10);
                    if !backend_db::prefix_key_exists(pool, &k).await? {
                        break k;
                    }
                },
            };
            let url = match url.as_deref().map(crate::admin::validate_upstream_url).transpose() {
                Ok(u) => u,
                Err(m) => bail!("invalid --url: {m}"),
            };
            let backend_id = match backend_id.as_deref().map(crate::admin::validate_backend_id).transpose() {
                Ok(b) => b,
                Err(m) => bail!("invalid --backend-id: {m}"),
            };
            let b = backend_db::insert_backend(pool, &key, &name, !inactive).await?;
            if url.is_some() || backend_id.is_some() {
                let patch = backend_db::BackendPatch { upstream_url: url, backend_id, ..Default::default() };
                backend_db::update_backend(pool, b.id, &patch).await?;
            }
            println!(
                "created backend id={} prefix_key={} name={:?} active={}",
                b.id, b.prefix_key, b.name, b.is_active
            );
            println!("the nginx map is regenerated by the running service within a minute (render_nginx_map)");
        }
        BackendCmd::Activate { prefix_key } => set_active(pool, &prefix_key, true).await?,
        BackendCmd::Deactivate { prefix_key } => set_active(pool, &prefix_key, false).await?,
    }
    Ok(())
}

async fn set_active(pool: &PgPool, prefix_key: &str, active: bool) -> Result<()> {
    if !backend_db::set_backend_active(pool, prefix_key, active).await? {
        bail!("no backend with prefix_key {prefix_key:?}");
    }
    println!("backend {prefix_key} is now {}", if active { "active" } else { "inactive" });
    Ok(())
}

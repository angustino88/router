//! nginx backend map files.
//!
//! nginx maps `$tenant_id` (the `<prefix_key>` of `/t/<prefix_key>/...`) to a backend URL from two files:
//!
//! * the static, git-managed `backends.map` (read-only here, normally only comments), and
//! * `backends.admin.map`, generated from the database (active backends that have an `upstream_url`) into the
//!   directory shared with the nginx container.
//!
//! The nginx container (`deploy/nginx/watch-maps.sh`) watches both, runs `nginx -t` and reloads; it writes the
//! outcome to `nginx-status.json`. A forced reload is requested by creating `reload.request`.

use std::{
    collections::BTreeMap,
    fs,
    path::{Path, PathBuf},
};

use serde_json::{json, Value};

pub const GENERATED_FILE: &str = "backends.admin.map";
const STATUS_FILE: &str = "nginx-status.json";
const RELOAD_REQUEST: &str = "reload.request";

pub struct NginxMaps {
    git_file: PathBuf,
    admin_dir: PathBuf,
    /// Serialises writers of the generated file inside this process.
    pub lock: tokio::sync::Mutex<()>,
}

/// One `prefix_key -> target` line of a map file.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct MapEntry {
    pub prefix_key: String,
    pub target: String,
}

/// `key value;` lines of an nginx map include; comments and blank lines ignored.
pub fn parse_map(text: &str) -> Vec<MapEntry> {
    let mut out = Vec::new();
    for line in text.lines() {
        let line = line.split('#').next().unwrap_or("").trim();
        let Some(line) = line.strip_suffix(';') else { continue };
        let mut parts = line.split_whitespace();
        if let (Some(k), Some(v), None) = (parts.next(), parts.next(), parts.next()) {
            out.push(MapEntry { prefix_key: k.to_string(), target: v.trim_matches('"').to_string() });
        }
    }
    out
}

/// Content of the generated map. Keys also present in the static file are skipped (nginx refuses duplicate
/// map keys, and the static file is the explicit operator override). Returns `(content, written, skipped)`.
pub fn render_map(rows: &[(String, String)], git_keys: &[String]) -> (String, Vec<MapEntry>, Vec<(String, String)>) {
    let mut content = String::from(
        "# Generated by the Router from the backend URLs on /admin/. Do not edit: changes are overwritten.\n",
    );
    let mut written = Vec::new();
    let mut skipped = Vec::new();
    let mut seen = std::collections::HashSet::new();
    for (key, url) in rows {
        if git_keys.iter().any(|g| g == key) {
            skipped.push((key.clone(), "declared in the static backends.map".to_string()));
            continue;
        }
        if !seen.insert(key.clone()) {
            continue;
        }
        content.push_str(&format!("{key} {url};\n"));
        written.push(MapEntry { prefix_key: key.clone(), target: url.clone() });
    }
    (content, written, skipped)
}

impl NginxMaps {
    pub fn new(git_file: &str, admin_dir: &str) -> NginxMaps {
        NginxMaps {
            git_file: PathBuf::from(git_file),
            admin_dir: PathBuf::from(admin_dir),
            lock: tokio::sync::Mutex::new(()),
        }
    }

    pub fn git_file(&self) -> &Path {
        &self.git_file
    }

    pub fn generated_file(&self) -> PathBuf {
        self.admin_dir.join(GENERATED_FILE)
    }

    /// Entries of the static file (empty when it is missing).
    pub fn git_entries(&self) -> Vec<MapEntry> {
        fs::read_to_string(&self.git_file).map(|t| parse_map(&t)).unwrap_or_default()
    }

    /// Entries of the generated file as it is on disk.
    pub fn generated_entries(&self) -> Vec<MapEntry> {
        fs::read_to_string(self.generated_file()).map(|t| parse_map(&t)).unwrap_or_default()
    }

    /// Rewrites the generated map (atomically, and only when the content changes).
    /// Result: `{"entries", "changed", "skipped": [{"prefix_key", "reason"}], "file"}`.
    pub fn write_generated(&self, rows: &[(String, String)]) -> Result<Value, String> {
        let git_keys: Vec<String> = self.git_entries().into_iter().map(|e| e.prefix_key).collect();
        let (content, written, skipped) = render_map(rows, &git_keys);
        let path = self.generated_file();
        let changed = fs::read_to_string(&path).map(|old| old != content).unwrap_or(true);
        if changed {
            fs::create_dir_all(&self.admin_dir).map_err(|e| format!("create {}: {e}", self.admin_dir.display()))?;
            let tmp = self.admin_dir.join(format!(".{GENERATED_FILE}.tmp"));
            fs::write(&tmp, &content).map_err(|e| format!("write {}: {e}", tmp.display()))?;
            fs::rename(&tmp, &path).map_err(|e| format!("rename to {}: {e}", path.display()))?;
        }
        Ok(json!({
            "entries": written.len(),
            "changed": changed,
            "skipped": skipped.iter().map(|(k, r)| json!({"prefix_key": k, "reason": r})).collect::<Vec<_>>(),
            "file": path.display().to_string(),
        }))
    }

    /// Asks the nginx watcher to test and reload even when no map changed.
    pub fn request_reload(&self) -> Result<(), String> {
        let path = self.admin_dir.join(RELOAD_REQUEST);
        fs::write(&path, chrono_like_now()).map_err(|e| format!("write {}: {e}", path.display()))
    }

    pub fn reload_pending(&self) -> bool {
        self.admin_dir.join(RELOAD_REQUEST).exists()
    }

    /// Last outcome written by the watcher, `None` until nginx reports.
    pub fn nginx_status(&self) -> Option<Value> {
        let text = fs::read_to_string(self.admin_dir.join(STATUS_FILE)).ok()?;
        serde_json::from_str(&text).ok()
    }

    /// Full routing table (static entries first) with the source of each entry.
    pub fn routing_table(&self) -> Vec<Value> {
        let mut table: BTreeMap<String, Value> = BTreeMap::new();
        for e in self.generated_entries() {
            table.insert(
                e.prefix_key.clone(),
                json!({"prefix_key": e.prefix_key, "target": e.target, "source": "database"}),
            );
        }
        for e in self.git_entries() {
            table
                .insert(e.prefix_key.clone(), json!({"prefix_key": e.prefix_key, "target": e.target, "source": "git"}));
        }
        table.into_values().collect()
    }
}

/// Seconds since the epoch, as text (content of the reload request; only its presence matters).
fn chrono_like_now() -> String {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs().to_string())
        .unwrap_or_default()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parse_static_map() {
        let text = "# header\n\n  abc   10.0.0.1:8001;  # note\nxyz https://h.example:443;\nbad line\n# old 1.2.3.4;\n";
        assert_eq!(
            parse_map(text),
            vec![
                MapEntry { prefix_key: "abc".into(), target: "10.0.0.1:8001".into() },
                MapEntry { prefix_key: "xyz".into(), target: "https://h.example:443".into() },
            ]
        );
    }

    #[test]
    fn render_skips_static_keys() {
        let rows = vec![("a".to_string(), "http://h1:1".to_string()), ("b".to_string(), "https://h2".to_string())];
        let (content, written, skipped) = render_map(&rows, &["b".to_string()]);
        assert!(content.contains("a http://h1:1;\n"));
        assert!(!content.contains("h2"));
        assert_eq!(written.len(), 1);
        assert_eq!(skipped[0].0, "b");
        assert_eq!(parse_map(&content), written);
    }

    #[test]
    fn write_only_when_changed() {
        let dir = std::env::temp_dir().join(format!("router-maps-{}", uuid::Uuid::new_v4()));
        let maps = NginxMaps::new(dir.join("missing.map").to_str().unwrap(), dir.to_str().unwrap());
        let rows = vec![("k".to_string(), "http://h:1".to_string())];
        assert_eq!(maps.write_generated(&rows).unwrap()["changed"], true);
        assert_eq!(maps.write_generated(&rows).unwrap()["changed"], false);
        assert_eq!(maps.routing_table()[0]["source"], "database");
        assert!(!maps.reload_pending());
        maps.request_reload().unwrap();
        assert!(maps.reload_pending());
        let _ = fs::remove_dir_all(dir);
    }
}
